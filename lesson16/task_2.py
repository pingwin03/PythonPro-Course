#
# Różnica:
# Klient to strona inicjująca komunikację – wysyła żądanie o dane lub wykonanie konkretnej akcji.
# Serwer to strona pasywna, która stale nasłuchuje na przychodzące żądania, przetwarza je 
# i odsyła odpowiedź z rezultatem.
#
# Przykłady:
# - Klient: Przeglądarka internetowa Google Chrome, Mozilla Firefox lub aplikacja mobilna Spotify.
# - Serwer: Komputer (host) firmy hostingowej, na którym działa kod aplikacji webowej 
#   i baza danych (np. serwer obsługujący stronę facebook.com).